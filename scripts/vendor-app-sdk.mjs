// Turns the MCP Apps browser bundle (one ES module ending in `export{...}`)
// into a classic script that sets globalThis.McpApps, and writes it as a
// string the UI resources can inline. Inlining keeps each card self-contained,
// so it works under a host's default sandbox CSP without extra domains.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

// The package's exports map hides package.json, so resolve the entry it does export.
const appWithDeps = fileURLToPath(import.meta.resolve("@modelcontextprotocol/ext-apps/app-with-deps"));
const src = readFileSync(appWithDeps, "utf8");

const m = src.match(/export\s*\{([^}]*)\}\s*;?\s*$/);
if (!m) throw new Error("vendor-app-sdk: could not find the bundle's export list");
const pairs = m[1]
  .split(",")
  .map((s) => s.trim())
  .filter(Boolean)
  .map((s) => {
    const [local, exported] = s.split(/\s+as\s+/);
    return `${JSON.stringify(exported ?? local)}:${local}`;
  });
const classic = `(()=>{${src.slice(0, m.index)};globalThis.McpApps={${pairs.join(",")}};})();`;

const out = path.join(process.cwd(), "src/mcp/ui/app-sdk.generated.ts");
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, `// Generated by scripts/vendor-app-sdk.mjs from @modelcontextprotocol/ext-apps. Do not edit.\nexport const APP_SDK = ${JSON.stringify(classic)};\n`);
console.log(`vendor-app-sdk: wrote ${path.relative(process.cwd(), out)} (${Math.round(classic.length / 1024)} KB)`);
